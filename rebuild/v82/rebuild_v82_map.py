def split_bullets(s):
    """把 snippet 按 ①②③ 拆成摘要条目；无编号则整体一条。"""
    s = (s or '').strip()
    if not s:
        return []
    parts = re.split(r'(?=[①②③④⑤])', s)
    out = []
    for x in parts:
        x = x.strip().rstrip('；;').strip()
        if x:
            out.append(x)
    return out

def fmt_related(rel):
    if not rel:
        return '（原文未标注）'
    return '+'.join('%s%d' % (r['market'], r['count']) for r in rel)

